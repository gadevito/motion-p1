#!/usr/bin/env python3
"""
E9 — campaign (`protocol/paper4/E9.md`, signed 2026-11-07, commit efbecae).
============================================================================
Written after the signature. It imports the frozen code without changing it: `p4b.py` (SHA-256
926061038a7472a3) and `e9.py` (4dd5628af8879511), both as at commit 2821669. It refuses to start if either
fingerprint differs, if the pre-registration is not signed, if the signed commit is not an ancestor of HEAD,
if code or pre-registration have uncommitted changes, or if the preflight log has any failure other than the
one expected after the signature (the guard that refuses test metrics while the signature line is blank).

For each of 3 cities x 4 levels of f x 5 seeds x 3 arms (180 trainings), in a fixed order:

  * Setup on the signed perimeter: per-city grid (11, 11, 15), node sets by deficit on (f, 20%, 80% - f), no
    static attribute, lr 1e-3, no dropout; road graph for G1, degree- and connectivity-preserving swaps with
    G1's weights permuted for G1-rand(deg);
  * U = 1,000 updates, 11 checkpoints at round(U*i/11), selection on validation-hidden nodes;
  * per-cell predictions, float32, at the selected checkpoint: val_hidden.npz, test_hidden.npz,
    test_observed.npz (as in E11);
  * run.json: configuration and fingerprint, setup fingerprints, shares, geometry covariates (cell side,
    median distance test-hidden -> observed, test blocks), randomised-graph record, trajectory, selected
    checkpoint, times, file fingerprints, commit.

No metric is aggregated here: CONGELAMENTO_E9.md is generated by a separate script.

Each run writes to paper4/runs/e9/<config-fingerprint>/. An existing folder blocks the launch, unless it holds a
complete run.json and --resume is given (the run is skipped, never overwritten). A folder without run.json (an
interrupted run) always stops the campaign. A training time outside [0.2x, 10x] of the isolated time of its arm
on Madrid stops the campaign. --shard i/n splits the plan across processes for calendar time.

Usage (from the worktree root, after the preflight on the signed commit):

    $PY paper4/code/e9.py preflight              # keep a copy of the signed e9_preflight.log first
    $PY paper4/code/e9_campagna.py --preflight-log <log> --check-only
    $PY paper4/code/e9_campagna.py --preflight-log <log> [--shard 1/2]
"""
import argparse
import json
import re
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import p4b  # noqa: E402
import e9  # noqa: E402

FROZEN = {"p4b.py": "926061038a7472a3", "e9.py": "4dd5628af8879511"}
SIGNED_COMMIT = "efbecae"
U = 1000
CHECKPOINTS = [round(U * i / 11) for i in range(1, 12)]
BASE = e9.RUNS / "e9"
ISOLATED = {"G0": 89.0, "G1": 169.0, "G1-rand(deg)": 135.9}   # Madrid, f = 40%, seconds (E9.md, Cost)


def fail(msg):
    print(f"STOP: {msg}", file=sys.stderr, flush=True)
    sys.exit(2)


def checks(preflight_log):
    here = Path(__file__).resolve().parent
    for name, fp in FROZEN.items():
        got = p4b.sha256(here / name, 16)
        if got != fp:
            fail(f"{name} fingerprint {got} differs from the frozen {fp}")
    p4b.require_signed(e9.PREREG)
    if subprocess.run(["git", "-C", str(p4b.ROOT), "merge-base", "--is-ancestor", SIGNED_COMMIT, "HEAD"]).returncode:
        fail(f"the signed commit {SIGNED_COMMIT} is not an ancestor of HEAD")
    dirty = subprocess.check_output(["git", "-C", str(p4b.ROOT), "status", "--porcelain", "--", "paper4/code",
                                     "protocol/paper4/E9.md"], text=True).strip()
    if dirty:
        fail(f"uncommitted changes in the code or the pre-registration:\n{dirty}")
    txt = Path(preflight_log).read_text()
    fails = [ln for ln in txt.splitlines() if ln.startswith("[FAIL]")]
    expected = [ln for ln in fails if "test metrics refused while the E9 signature line is blank" in ln]
    if "(code dirty: False)" not in txt or len(fails) != len(expected) or len(expected) > 1 \
            or not re.search(r"PREFLIGHT: [01] failure\(s\)", txt):
        fail(f"{preflight_log}: preflight not passed on a clean tree ({len(fails)} failure(s))")
    m = re.search(r"code p4b\.py (\w+) · e9\.py (\w+)", txt)
    if not m or (m.group(1), m.group(2)) != (FROZEN["p4b.py"], FROZEN["e9.py"]):
        fail(f"{preflight_log}: preflight not run on the frozen code")
    return p4b.sha256(preflight_log, 16)


def one_run(city, f, seed, arm, preflight_fp, resume):
    cfg = {"experiment": "E9", "city": city, "f": f, "seed": seed, "arm": arm, "U": U, "checkpoints": CHECKPOINTS,
           "grid": e9.GRID[city], "targets": list(e9.targets(f)), "perimeter": "no static attribute, lr 1e-3, no dropout",
           "frozen_code": FROZEN, "prereg_signed_commit": SIGNED_COMMIT}
    d = BASE / p4b.fingerprint(cfg)
    if d.exists():
        if (d / "run.json").exists() and resume:
            return "skipped", d
        if not (d / "run.json").exists():
            fail(f"{d} exists without run.json: interrupted run, to be reported, not repaired")
        fail(f"{d} exists: launch blocked (use --resume to skip complete runs)")
    d.mkdir(parents=True)
    t0 = time.perf_counter()
    su = e9.setup(city, f, seed)
    A, info = e9.adjacency(su, arm)
    o = p4b.train(su, arm, A, U=U, checkpoints=CHECKPOINTS)
    if o["updates"] != U or o["hidden_in_batches"] != 0:
        fail(f"{city} f={f} s{seed} {arm}: updates {o['updates']}, hidden in batches {o['hidden_in_batches']}")
    if not (0.2 * ISOLATED[arm] <= o["seconds"] <= 10 * ISOLATED[arm]):
        fail(f"{city} f={f} s{seed} {arm}: training time {o['seconds']:.1f} s outside [0.2x, 10x] of {ISOLATED[arm]} s")
    sel = o["selected"]
    o["net"].load_state_dict(o["states"][sel])
    files = {}
    for name, origins, tgt in (("val_hidden", su.va, su.val), ("test_hidden", su.te, su.test),
                               ("test_observed", su.te, su.obs)):
        P, Y = p4b.predict(o["net"], su, o["A"], origins, su.obs, tgt)
        path = d / f"{name}.npz"
        np.savez_compressed(path, p=P.astype("float32"), y=Y.astype("int8"), origins=origins.astype("int32"),
                            nodes=np.where(tgt)[0].astype("int32"))
        files[name] = {"file": path.name, "sha256": p4b.sha256(path, 16)}
    geo = su.geometry(); geo["test_blocks"] = int(len(np.unique(su.cells[su.test])))
    if arm == "G1":
        info["mean_geo_length_m"] = float(p4b.geo_lengths(su.al["graph"], su.kept, su.al["coords"]).mean())
    rec = {"config": cfg, "config_fingerprint": p4b.fingerprint(cfg), "preflight_log_fingerprint": preflight_fp,
           "K": su.K, "grid": su.G, "shares": su.shares(), "geometry": geo, "setup": su.fingerprints(),
           "class_weights": su.W.tolist(), "purged": su.purged,
           "origins": {"train": len(su.tr), "val": len(su.va), "test": len(su.te)}, "graph": info,
           "trajectory": o["trajectory"], "selected_update": sel, "init_seed": o["init_seed"],
           "train_seconds": o["seconds"], "run_seconds": time.perf_counter() - t0, "files": files}
    p4b.record(d, rec)
    return "done", d


def main():
    ap = argparse.ArgumentParser(description="E9 campaign (after the signature)")
    ap.add_argument("--preflight-log", required=True)
    ap.add_argument("--shard", default="1/1", help="i/n: this process runs every n-th run starting at i")
    ap.add_argument("--resume", action="store_true", help="skip runs with a complete run.json")
    ap.add_argument("--check-only", action="store_true", help="run the start checks and print the plan; no training")
    a = ap.parse_args()
    pf = checks(a.preflight_log)
    i, n = (int(x) for x in a.shard.split("/"))
    plan = [(c, f, s, arm) for c in e9.CITIES for f in e9.LEVELS for s in e9.SEEDS for arm in e9.ARMS]
    mine = [r for k, r in enumerate(plan) if k % n == i - 1]
    if a.check_only:
        print(f"checks passed (preflight log {pf}); shard {i}/{n}: {len(mine)} of {len(plan)} runs; U = {U}, "
              f"checkpoints {CHECKPOINTS}; grids {e9.GRID}; output {BASE}")
        return 0
    BASE.mkdir(parents=True, exist_ok=True)
    log = BASE / f"campagna_shard{i}of{n}.log"
    with open(log, "a") as fh:
        fh.write(f"{datetime.now(timezone.utc).isoformat()} start shard {i}/{n}: {len(mine)} of {len(plan)} runs; "
                 f"commit {p4b.git_commit()[0]}; preflight {pf}\n")
        for k, (c, f, s, arm) in enumerate(mine, 1):
            status, d = one_run(c, f, s, arm, pf, a.resume)
            line = f"{datetime.now(timezone.utc).isoformat()} [{k}/{len(mine)}] {status} {c} f={f} seed {s} {arm} -> {d.name}"
            print(line, flush=True); fh.write(line + "\n"); fh.flush()
        fh.write(f"{datetime.now(timezone.utc).isoformat()} end shard {i}/{n}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
