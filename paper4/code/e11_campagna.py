#!/usr/bin/env python3
"""
E11 — campaign (`protocol/paper4/E11.md`, signed 2026-11-06, commit 22e7fe8).
===============================================================================
Written after the signature, as the pre-registration requires. It imports the frozen pipeline without
changing it: `p4b.py` (SHA-256 926061038a7472a3) and `e11.py` (f68952c3095cf335), both as at commit 4b298d1.
The script refuses to start if either fingerprint differs, if the pre-registration is not signed, or if the
preflight log given with --preflight-log has any failure on a clean tree other than the one expected after the
signature (the guard that refuses test metrics while the signature line is blank).

For each of the 12 configurations x 5 seeds x 4 arms (240 trainings), in a fixed order:

  * Setup on the signed perimeter (smallest grid G >= 6 with >= 20 occupied cells, node sets by deficit on
    40/20/40, no static attribute, lr 1e-3, no dropout);
  * U = 1,000 updates, 11 checkpoints at round(U*i/11), selection on validation-hidden nodes;
  * per-cell predictions, float32, at the selected checkpoint:
        val_hidden.npz   validation origins, input = observed, targets = validation-hidden
        test_hidden.npz  test origins,       input = observed, targets = test-hidden
        test_observed.npz test origins,      input = observed, targets = observed
  * run.json: configuration and its fingerprint, setup fingerprints, shares, geometry covariates,
    randomised-graph record, trajectory, selected checkpoint, times, file fingerprints, commit.

No metric is aggregated here: CONGELAMENTO_E11.md is generated by a separate script from these files.

Each run writes to paper4/runs/e11/<config-fingerprint>/. An existing folder blocks the launch, unless it holds
a complete run.json and --resume is given, in which case that run is skipped (never overwritten). An existing
folder without run.json (an interrupted run) always stops the campaign: it is reported, not repaired.

Wall time: a run outside [0.2x, 10x] of the isolated time of its arm (e11_costi.json) stops the campaign,
to catch a run routed to the wrong branch. Concurrent processes (--shard i/n) are allowed for calendar time.

Usage (from the worktree root, after the preflight on the signed commit):

    $PY paper4/code/e11.py preflight            # writes paper4/runs/e11_preflight.log (keep a copy of the
                                                #   signed one first: its fingerprint is in the signature line)
    $PY paper4/code/e11_campagna.py --preflight-log paper4/runs/e11_preflight.log
    $PY paper4/code/e11_campagna.py --preflight-log ... --shard 1/2     # optional, one shard per process
    $PY paper4/code/e11_campagna.py --preflight-log ... --check-only    # start checks only, no training
"""
import argparse
import json
import re
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import p4b  # noqa: E402
import e11  # noqa: E402

FROZEN = {"p4b.py": "926061038a7472a3", "e11.py": "f68952c3095cf335"}
SIGNED_COMMIT = "22e7fe8"
U = 1000
CHECKPOINTS = [round(U * i / 11) for i in range(1, 12)]
BASE = e11.RUNS / "e11"
ISOLATED = {"G0": 11.5, "G1": 14.3, "G1-rand(deg)": 14.3, "G1-rand(edges)": 14.4}   # e11_costi.json, seconds


def fail(msg):
    print(f"STOP: {msg}", file=sys.stderr, flush=True)
    sys.exit(2)


def checks(preflight_log):
    here = Path(__file__).resolve().parent
    for name, fp in FROZEN.items():
        got = p4b.sha256(here / name, 16)
        if got != fp:
            fail(f"{name} fingerprint {got} differs from the frozen {fp}")
    p4b.require_signed(e11.PREREG)
    anc = subprocess.run(["git", "-C", str(p4b.ROOT), "merge-base", "--is-ancestor", SIGNED_COMMIT, "HEAD"])
    if anc.returncode != 0:
        fail(f"the signed commit {SIGNED_COMMIT} is not an ancestor of HEAD")
    dirty = subprocess.check_output(["git", "-C", str(p4b.ROOT), "status", "--porcelain", "--", "paper4/code",
                                     "protocol/paper4/E11.md"], text=True).strip()
    if dirty:
        fail(f"uncommitted changes in the code or the pre-registration:\n{dirty}")
    txt = Path(preflight_log).read_text()
    # After the signature the frozen preflight reports one expected failure: its guard asserts that test
    # metrics are refused while the signature line is blank, and the line is now complete (require_signed
    # passed above). Every other assertion must pass.
    fails = [ln for ln in txt.splitlines() if ln.startswith("[FAIL]")]
    expected = [ln for ln in fails if "test metrics refused while the E11 signature line is blank" in ln]
    if "(code dirty: False)" not in txt or len(fails) != len(expected) or len(expected) > 1 \
            or not re.search(r"PREFLIGHT: [01] failure\(s\)", txt):
        fail(f"{preflight_log}: preflight not passed on a clean tree ({len(fails)} failure(s))")
    m = re.search(r"code p4b\.py (\w+) · e11\.py (\w+)", txt)
    if not m or (m.group(1), m.group(2)) != (FROZEN["p4b.py"], FROZEN["e11.py"]):
        fail(f"{preflight_log}: preflight not run on the frozen code")
    return p4b.sha256(preflight_log, 16)


def one_run(city, tag, seed, arm, preflight_fp, resume):
    cfg = {"experiment": "E11", "city": city, "configuration": tag, "seed": seed, "arm": arm, "U": U,
           "checkpoints": CHECKPOINTS, "perimeter": "no static attribute, lr 1e-3, no dropout",
           "grid": "smallest G >= 6 with >= 20 occupied cells", "node_sets": "deficit on 40/20/40",
           "frozen_code": FROZEN, "prereg_signed_commit": SIGNED_COMMIT}
    d = BASE / p4b.fingerprint(cfg)
    if d.exists():
        if (d / "run.json").exists() and resume:
            return "skipped", d
        if not (d / "run.json").exists():
            fail(f"{d} exists without run.json: interrupted run, to be reported, not repaired")
        fail(f"{d} exists: launch blocked (use --resume to skip complete runs)")
    d.mkdir(parents=True)
    t0 = time.perf_counter()
    su = p4b.Setup(city, e11.graph_path(city, tag), seed=seed)
    adj = e11.adjacency(su, arm)
    A, info = adj[0], (adj[1] if len(adj) > 1 else {})
    o = p4b.train(su, arm, A, U=U, checkpoints=CHECKPOINTS)
    if o["updates"] != U or o["hidden_in_batches"] != 0:
        fail(f"{city} {tag} s{seed} {arm}: updates {o['updates']}, hidden in batches {o['hidden_in_batches']}")
    sel = o["selected"]
    o["net"].load_state_dict(o["states"][sel])
    files = {}
    for name, origins, tgt in (("val_hidden", su.va, su.val), ("test_hidden", su.te, su.test),
                               ("test_observed", su.te, su.obs)):
        P, Y = p4b.predict(o["net"], su, o["A"], origins, su.obs, tgt)
        path = d / f"{name}.npz"
        np.savez_compressed(path, p=P.astype("float32"), y=Y.astype("int8"), origins=origins.astype("int32"),
                            nodes=np.where(tgt)[0].astype("int32"))
        z = np.load(path)
        files[name] = {"file": path.name, "sha256": p4b.sha256(path, 16),
                       "reconstructs": bool(p4b.wce_np(z["p"], z["y"], su.W) == p4b.wce_np(P.astype("float32"), Y, su.W))}
    secs = time.perf_counter() - t0
    if not (0.2 * ISOLATED[arm] <= o["seconds"] <= 10 * ISOLATED[arm]):
        fail(f"{city} {tag} s{seed} {arm}: training time {o['seconds']:.1f} s outside [0.2x, 10x] of "
             f"{ISOLATED[arm]} s")
    rec = {"config": cfg, "config_fingerprint": p4b.fingerprint(cfg), "preflight_log_fingerprint": preflight_fp,
           "K": su.K, "grid": su.G, "shares": su.shares(), "geometry": su.geometry(), "setup": su.fingerprints(),
           "class_weights": su.W.tolist(), "purged": su.purged, "origins": {"train": len(su.tr), "val": len(su.va),
                                                                          "test": len(su.te)},
           "graph": info, "trajectory": o["trajectory"], "selected_update": sel, "init_seed": o["init_seed"],
           "train_seconds": o["seconds"], "run_seconds": secs, "files": files}
    if arm != "G0":
        g = su.al["graph"] if arm == "G1" else adj[2]
        rec["graph"]["mean_geo_length_m"] = float(p4b.geo_lengths(g, su.kept, su.al["coords"]).mean())
    p4b.record(d, rec)
    return "done", d


def main():
    ap = argparse.ArgumentParser(description="E11 campaign (after the signature)")
    ap.add_argument("--preflight-log", required=True)
    ap.add_argument("--shard", default="1/1", help="i/n: this process runs every n-th run starting at i")
    ap.add_argument("--resume", action="store_true", help="skip runs with a complete run.json")
    ap.add_argument("--check-only", action="store_true", help="run the start checks and print the plan; no training")
    a = ap.parse_args()
    pf = checks(a.preflight_log)
    i, n = (int(x) for x in a.shard.split("/"))
    plan = [(c, t, s, arm) for c, t, _ in e11.CONFIGS for s in e11.SEEDS for arm in e11.ARMS]
    mine = [r for k, r in enumerate(plan) if k % n == i - 1]
    if a.check_only:
        print(f"checks passed (preflight log {pf}); shard {i}/{n}: {len(mine)} of {len(plan)} runs; "
              f"U = {U}, checkpoints {CHECKPOINTS}; output {BASE}")
        return 0
    BASE.mkdir(parents=True, exist_ok=True)
    log = BASE / f"campagna_shard{i}of{n}.log"
    with open(log, "a") as fh:
        fh.write(f"{datetime.now(timezone.utc).isoformat()} start shard {i}/{n}: {len(mine)} of {len(plan)} runs; "
                 f"commit {p4b.git_commit()[0]}; preflight {pf}\n")
        for k, (c, t, s, arm) in enumerate(mine, 1):
            status, d = one_run(c, t, s, arm, pf, a.resume)
            line = f"{datetime.now(timezone.utc).isoformat()} [{k}/{len(mine)}] {status} {c} {t} seed {s} {arm} -> {d.name}"
            print(line, flush=True); fh.write(line + "\n"); fh.flush()
        fh.write(f"{datetime.now(timezone.utc).isoformat()} end shard {i}/{n}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
