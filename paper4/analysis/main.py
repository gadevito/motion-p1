def diff_json(a, b, path=""):
    out = []
    if isinstance(a, dict) and isinstance(b, dict):
        for k in sorted(set(a) | set(b)):
            if path == "" and k in VOLATILE:
                continue
            if k not in a or k not in b:
                out.append(f"{path}/{k}: present on one side only")
            else:
                out += diff_json(a[k], b[k], f"{path}/{k}")
    elif isinstance(a, list) and isinstance(b, list) and len(a) == len(b):
        for i, (x, y) in enumerate(zip(a, b)):
            out += diff_json(x, y, f"{path}[{i}]")
    elif a != b and not (isinstance(a, float) and isinstance(b, float) and a != a and b != b):
        out.append(f"{path}: {a!r} != {b!r}")
    return out


def masked(path):
    t = Path(path).read_text()
    t = t[:t.find(NOTE_MARK)] if NOTE_MARK in t else t
    return [ln for ln in t.splitlines() if not ln.startswith("Generated by ")]


def step_regenerate(report, names, work):
    ok = True
    report.append("## 2. Regeneration from the run folders\n\n| Experiment | Markdown | JSON | Other files |\n|---|---|---|---|")
    for name in names:
        e = EXPERIMENTS[name]; out = work / "congelamenti" / name; out.mkdir(parents=True)
        try:
            run_generator(name, out)
        except BaseException as exc:  # noqa: BLE001 - a STOP of a generator is a failure of this step
            ok = False; report.append(f"| {name} | generator stopped: {exc!r} | | |"); continue
        cells = []
        for fn in e["files"]:
            new, old = out / fn, FROZEN / fn
            if not new.exists():
                cells.append("missing"); ok = False; continue
            if fn.endswith(".json"):
                d = diff_json(json.loads(old.read_text()), json.loads(new.read_text()))
                cells.append("every number identical" if not d else f"{len(d)} differences: " + "; ".join(d[:5]))
            elif fn.endswith(".md"):
                d = [i for i, (x, y) in enumerate(zip(masked(old), masked(new))) if x != y]
                d += ["length"] if len(masked(old)) != len(masked(new)) else []
                cells.append("identical (Generated line masked)" if not d else f"{len(d)} lines differ")
            else:
                same = sha(old) == sha(new)
                cells.append("identical bytes" if same else "DIFFERENT bytes")
                d = [] if same else ["bytes"]
            ok &= not d
        while len(cells) < 3:
            cells.append("—")
        report.append(f"| {name} | " + " | ".join(cells) + " |")
    report.append("")
    return ok


