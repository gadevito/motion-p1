NUM = re.compile(r"(?<![\w.,/#])[−-]?\d{1,3}(?:,\d{3})+(?:\.\d+)?(?![\w])|(?<![\w.,/#])[−-]?\d+(?:\.\d+)?(?![\w.]\w|\w)")


def leaves(x):
    """Numeric leaves, plus the quantities the generators derive when they print: agreement shares
    (agree / pairs) and means of numeric lists (seed means)."""
    if isinstance(x, dict):
        if isinstance(x.get("agree"), (int, float)) and x.get("pairs"):
            yield x["agree"] / x["pairs"]
        for v in x.values():
            yield from leaves(v)
    elif isinstance(x, list):
        nums = [v for v in x if isinstance(v, (int, float)) and not isinstance(v, bool)]
        if nums and len(nums) == len(x):
            yield float(sum(nums) / len(nums))
        for v in x:
            yield from leaves(v)
    elif isinstance(x, str):
        # deliverable values and differences in the comparison table of CONGELAMENTO_4A ("0,542", "differs (-0.009)")
        m = re.fullmatch(r"[+-]?\d+(?:,\d+)?", x) or re.fullmatch(r"differs \(([+-]?\d+(?:\.\d+)?)\)", x)
        if m:
            yield float((m.group(1) if m.groups() else m.group(0)).replace(",", "."))
    elif isinstance(x, bool):
        return
    elif isinstance(x, (int, float)):
        yield float(x)


def candidates(keys):
    """Every rounding the text may use of every value: as is, absolute, ×100 (shares as percentages),
    in thousands and millions, with 0-3 decimals and with or without thousands separators."""
    vals, out = set(), set()
    for k in keys:
        vals.update(v for v in leaves(json.loads((FROZEN / f"{k}_risultati.json").read_text())) if v == v)
    for v in vals:
        for x in {v, abs(v), 100 * v, abs(100 * v), abs(v) / 1e6, abs(v) / 1e3}:
            if abs(x) > 1e12:
                continue
            for d in range(5):
                s = f"{x:.{d}f}"
                out.add(s); out.add(f"{x:,.{d}f}")
            if x >= 10000:
                out.add(f"{round(x, -3):,.0f}")                             # "140,000" for 140,300
    return out


def norm(tok):
    return tok.replace("−", "-")


def strip_markup(text):
    text = re.sub(r"`[^`]*`", " ", text)                                   # code spans: paths, fingerprints
    text = re.sub(r"\[(?:ref:[^\]]*|[a-z]+\d{4}[a-z]*)\]", " ", text)        # citation markers
    text = re.sub(r"\b\d{4}-\d{2}-\d{2}\b", " ", text)                     # dates
    text = re.sub(r"\(\d{1,2}:\d{2}\)|\b\d{1,2}:\d{2}\b", " ", text)        # times of day
    text = re.sub(r"\b(?:RQ|E|G|D|P|RC|R|Q|U|L|V|C|N|S|W|k|h|f|q|t)\d+\w*", " ", text)  # labels and symbols
    text = re.sub(r"\b[0-9a-f]{7,16}\b", " ", text)                        # commit hashes
